let currentLang = 'sv';
const langChangeListeners = [];

function detectDefaultLang() {
    const stored = localStorage.getItem(I18N_STORAGE_KEY);
    if (stored === 'en' || stored === 'sv') return stored;
    const nav = (navigator.language || '').toLowerCase();
    return nav.startsWith('sv') ? 'sv' : 'en';
}

function t(key, vars = {}) {
    const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.en;
    let text = dict[key] ?? TRANSLATIONS.en[key] ?? key;
    Object.entries(vars).forEach(([k, v]) => {
        text = text.replace(`{${k}}`, String(v));
    });
    return text;
}

function commodityLabel(name) {
    const map = COMMODITY_LABELS[currentLang] || COMMODITY_LABELS.en;
    return map[name] || name;
}

function positionLabel(pos) {
    if (pos === 'Long') return t('posLong');
    if (pos === 'Short') return t('posShort');
    return t('posNeutral');
}

function applyTranslations() {
    document.documentElement.lang = currentLang;
    document.title = t('pageTitle');

    document.querySelectorAll('[data-i18n]').forEach((el) => {
        el.textContent = t(el.dataset.i18n);
    });
    document.querySelectorAll('[data-i18n-html]').forEach((el) => {
        el.innerHTML = t(el.dataset.i18nHtml);
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
        el.placeholder = t(el.dataset.i18nPlaceholder);
    });

    document.querySelectorAll('.lang-btn').forEach((btn) => {
        const active = btn.dataset.lang === currentLang;
        btn.classList.toggle('active', active);
        btn.setAttribute('aria-pressed', active ? 'true' : 'false');
    });
}

function setLang(lang) {
    if (lang !== 'en' && lang !== 'sv') return;
    currentLang = lang;
    localStorage.setItem(I18N_STORAGE_KEY, lang);
    applyTranslations();
    langChangeListeners.forEach((fn) => fn(lang));
}

function getLang() {
    return currentLang;
}

function onLangChange(fn) {
    langChangeListeners.push(fn);
}

function initI18n() {
    currentLang = detectDefaultLang();
    document.querySelectorAll('.lang-btn').forEach((btn) => {
        btn.addEventListener('click', () => setLang(btn.dataset.lang));
    });
    applyTranslations();
}

window.I18n = {
    t,
    commodityLabel,
    positionLabel,
    apply: applyTranslations,
    setLang,
    getLang,
    onLangChange,
    init: initI18n,
};
